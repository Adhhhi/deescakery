/**
 * Intelligent helper to provide an authentic, appetizing food photography URL
 * for any menu item based on its category, name, and flavour characteristics.
 */
export const getMenuItemVisual = (item: {
  category?: string;
  name: string;
  description?: string;
  image?: string;
}): string => {
  if (item.image) return item.image;

  const text = `${item.name} ${item.description || ''}`.toLowerCase();

  if (text.includes('biscoff') || text.includes('lotus') || text.includes('caramel') || text.includes('butterscotch')) {
    return 'https://images.unsplash.com/photo-1535141192574-5d4897c13136?auto=format&fit=crop&w=800&q=80';
  }
  if (text.includes('red velvet') || text.includes('crimson') || text.includes('cheesecake') || text.includes('cheese')) {
    return 'https://images.unsplash.com/photo-1586788680434-30d324b2d46f?auto=format&fit=crop&w=800&q=80';
  }
  if (
    text.includes('strawberry') ||
    text.includes('berry') ||
    text.includes('raspberry') ||
    text.includes('fruit') ||
    text.includes('mango') ||
    text.includes('kiwi') ||
    text.includes('orange') ||
    text.includes('pineapple') ||
    text.includes('citrus') ||
    text.includes('passion')
  ) {
    return 'https://images.unsplash.com/photo-1565958011703-44f9829ba187?auto=format&fit=crop&w=800&q=80';
  }
  if (
    text.includes('rasmalai') ||
    text.includes('saffron') ||
    text.includes('gulab jamun') ||
    text.includes('fusion') ||
    text.includes('paan') ||
    text.includes('gulkand') ||
    text.includes('pistachio') ||
    text.includes('kaju') ||
    text.includes('badam')
  ) {
    return 'https://images.unsplash.com/photo-1621303837174-89787a7d4729?auto=format&fit=crop&w=800&q=80';
  }
  if (text.includes('tres leches') || text.includes('tres') || text.includes('milk') || text.includes('pinata')) {
    return 'https://images.unsplash.com/photo-1533134242443-d4fd215305ad?auto=format&fit=crop&w=800&q=80';
  }
  if (
    text.includes('cupcake') ||
    item.category?.includes('cupcake') ||
    item.category === 'cheesy_bite' ||
    item.category === 'seasonal_magic' ||
    item.category === 'cupcake_lava' ||
    item.category === 'fusion_feast' ||
    item.category === 'chocoheaven' ||
    item.category === 'breakfast_cupcake'
  ) {
    if (text.includes('chocolate') || text.includes('nutella') || text.includes('fudge') || text.includes('snickers')) {
      return 'https://images.unsplash.com/photo-1576618148400-f54bed99fcfd?auto=format&fit=crop&w=800&q=80';
    }
    return 'https://images.unsplash.com/photo-1587668178277-295251f900ce?auto=format&fit=crop&w=800&q=80';
  }
  if (text.includes('brownie') || item.category === 'brownie_point' || item.category === 'boutique_brownies') {
    if (text.includes('nutella') || text.includes('loaded') || text.includes('ferrero') || text.includes('almond')) {
      return 'https://images.unsplash.com/photo-1515037893149-de7f840978e2?auto=format&fit=crop&w=800&q=80';
    }
    return 'https://images.unsplash.com/photo-1606313564200-e75d5e30476c?auto=format&fit=crop&w=800&q=80';
  }
  if (text.includes('blondie') || item.category === 'blondies') {
    return 'https://images.unsplash.com/photo-1509440159596-0249088772ff?auto=format&fit=crop&w=800&q=80';
  }
  if (text.includes('cookie') || text.includes('biscuit') || item.category?.includes('cookie')) {
    if (text.includes('brookie') || text.includes('stuffed') || text.includes('lava') || text.includes('gianduja')) {
      return 'https://images.unsplash.com/photo-1558961363-fa8fdf82db35?auto=format&fit=crop&w=800&q=80';
    }
    return 'https://images.unsplash.com/photo-1499636136210-6f4ee915583e?auto=format&fit=crop&w=800&q=80';
  }
  if (
    text.includes('chocolate') ||
    text.includes('truffle') ||
    text.includes('ferrero') ||
    text.includes('fudge') ||
    text.includes('cocoa') ||
    text.includes('oreo') ||
    text.includes('kitkat')
  ) {
    return 'https://images.unsplash.com/photo-1578985545062-69928b1d9587?auto=format&fit=crop&w=800&q=80';
  }
  if (text.includes('wedding') || text.includes('tier') || text.includes('floral')) {
    return 'https://images.unsplash.com/photo-1535254973040-607b474cb50d?auto=format&fit=crop&w=800&q=80';
  }
  return 'https://images.unsplash.com/photo-1535254973040-607b474cb50d?auto=format&fit=crop&w=800&q=80';
};


